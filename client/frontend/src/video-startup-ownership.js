import { inspectScreenStartupCodec, withScreenStartupBitrateHint, carryScreenStartupHint,
    withoutOwnedScreenStartupHint } from "./video-startup-bitrate.js";
import { rtcStatsEpochNow } from "./rtc-stats-clock.js";

// Only committed offer/answer rounds change ownership. Planning a round or
// rolling back a pending remote offer never consumes an existing owner.
export function createStartupHintOwnership({ now = rtcStatsEpochNow } = {}) {
    const peers = new WeakMap();
    const safe = callback => { try { return callback?.() === true; } catch { return false; } };
    const read = (description, owner, local = false) => inspectScreenStartupCodec(description, owner, owner.bitrateKbps, local);
    const live = (pc, owner) => {
        const remote = read(pc.currentRemoteDescription || pc.remoteDescription, owner);
        const local = read(pc.localDescription, owner, true);
        return safe(owner.stillOwned) && remote?.hint && remote.identity === owner.identity &&
            remote.security === owner.security && local?.security === owner.localSecurity &&
            [owner.identity, owner.localIdentity].includes(local.identity);
    };
    return {
        prepare(pc, description, seed) {
            const previous = peers.get(pc);
            let owner = null, next = description;
            if (previous?.owner && live(pc, previous.owner)) {
                const carried = carryScreenStartupHint(description, previous.owner);
                // Even an identical value arriving from the server is foreign.
                // Ownership requires that this transaction inserted the hint.
                if (carried && carried.sdp !== description.sdp) { owner = previous.owner; next = carried; }
            } else if (!previous && seed && safe(seed.stillEligible) && safe(seed.stillOwned)) {
                const at = now();
                const fresh = Number.isFinite(seed.expiresAt) && at >= seed.expiresAt - 1500 && at <= seed.expiresAt;
                const parsed = fresh && inspectScreenStartupCodec(description, seed);
                const local = parsed && read(pc.localDescription, seed, true);
                const prior = parsed && read(pc.currentRemoteDescription || pc.remoteDescription, seed);
                if (parsed?.security && parsed.primaryPayloadType === seed.payloadType && local?.security && local.selected.codec === parsed.selected.codec &&
                    prior?.security === parsed.security && !prior.hint && prior.identity === parsed.identity) {
                    const hinted = withScreenStartupBitrateHint(description, seed);
                    if (hinted.changed) {
                        owner = { mid: seed.mid, payloadType: seed.payloadType, bitrateKbps: seed.bitrateKbps,
                            codec: parsed.selected.codec, identity: parsed.identity, localIdentity: local.identity,
                            security: parsed.security, localSecurity: local.security,
                            stillOwned: seed.stillOwned };
                        next = { ...description, sdp: hinted.sdp };
                    }
                }
            }
            // A known hint may still be echoed in local SDP after retirement.
            // Retain its exact identity for wire sanitation, never for re-seeding.
            return {
                description: next,
                changed: next.sdp !== description.sdp,
                commit(applied) {
                    const parsed = owner && read(applied, owner);
                    const appliedOwned = parsed?.hint && parsed.identity === owner.identity && parsed.security === owner.security;
                    const accepted = appliedOwned && safe(owner.stillOwned);
                    // An accepted foreign hint supersedes historical provenance.
                    // Failed SRD or a rolled-back pending offer cannot erase it.
                    const foreignHint = !appliedOwned && /(?:^a=fmtp:[0-9]+ |;)\s*x-google-start-bitrate\s*=/mi.test(applied.sdp);
                    const known = foreignHint ? null : appliedOwned ? owner : previous?.known || previous?.owner;
                    if (previous || seed || owner) peers.set(pc, { owner: accepted ? owner : null, known });
                },
            };
        },
        serverDescription(pc, description) {
            const entry = peers.get(pc), known = entry?.known || entry?.owner;
            // This entry point only accepts descriptions generated by this browser.
            // A local format edit may preserve our old parameter even though carry
            // is no longer permitted; exact MID/PT/MIME/value provenance survives.
            return known ? withoutOwnedScreenStartupHint(description, known, true) : description;
        },
    };
}
