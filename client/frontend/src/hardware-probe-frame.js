import { frameMime } from "./media-frame-envelope.js";
const VP8 = new Uint8Array([0x10,0x02,0x00,0x9d,0x01,0x2a,0x08,0x00,0x08,0x00,0x00,0x47,0x08,0x85,0x85,0x88,0x85,0x84,0x88,0x02,0x02,0x00,0x0c,0x0d,0x60,0x00,0xfe,0xff,0xab,0x50,0x80]);
const H264 = new Uint8Array([0,0,0,1,0x67,0x42,0xc0,0x1f,0x0f,0xd9,0x1f,0x88,0x88,0x84,0,0,3,0,4,0,0,3,0,0xc8,0x3c,0x60,0xc9,0x20,0,0,0,1,0x68,0x87,0xcb,0x83,0xcb,0x20,0,0,0,1,0x65,0x88,0x84,0x0a,0xf2,0x62,0x80,0,0xa7,0xbe]);
export function hardwareProbeFrame(frame) {
    const mime = frameMime(frame);
    return mime === "video/h264" ? H264.slice() : mime === "video/vp8" && frame.type === "key" ? VP8.slice() : null;
}
